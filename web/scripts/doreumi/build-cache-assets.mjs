/** Keep immutable, byte-identical copies. Never remove older versions: open tabs can still request them. */
import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const sources = [
  ['DOREUMI_MODEL_URL', 'public/doreumi/doreumi-master.glb'],
  ['DOREUMI_RUNTIME_INDEX_URL', 'public/doreumi/motions/registry.runtime.json'],
];

export function immutableName(file, bytes) {
  const extension = path.extname(file);
  return `${path.basename(file, extension)}.${createHash('sha256').update(bytes).digest('hex')}${extension}`;
}

export async function buildCacheAssets(projectRoot = root, check = false) {
  const directory = path.join(projectRoot, 'public/doreumi/immutable');
  const moduleFile = path.join(projectRoot, 'src/lib/doreumi/motion-asset-urls.ts');
  const declarations = ['// Generated by scripts/doreumi/build-cache-assets.mjs. Keep old immutable files for open tabs.'];
  for (const [constant, source] of sources) {
    const bytes = await readFile(path.join(projectRoot, source));
    const name = immutableName(source, bytes);
    const target = path.join(directory, name);
    const current = await readFile(target).catch(error => { if (error.code === 'ENOENT') return null; throw error; });
    if (current && !current.equals(bytes)) throw new Error(`Immutable asset was modified: ${name}`);
    if (!current) {
      if (check) throw new Error('Cached assets are stale. Run: node scripts/doreumi/build-cache-assets.mjs');
      await mkdir(directory, { recursive: true });
      await writeFile(target, bytes, { flag: 'wx' });
    }
    declarations.push(`export const ${constant} = '/doreumi/immutable/${name}';`);
  }
  // Also guard retained historical files: an immutable URL must always identify its exact bytes.
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (!entry.isFile() || !/^.+\.[a-f0-9]{64}\.(glb|json)$/.test(entry.name)) throw new Error('Invalid immutable asset file');
    const bytes = await readFile(path.join(directory, entry.name));
    const original = entry.name.replace(/\.[a-f0-9]{64}(?=\.[^.]+$)/, '');
    if (immutableName(original, bytes) !== entry.name) throw new Error(`Immutable asset was modified: ${entry.name}`);
  }
  const expected = `${declarations.join('\n')}\n`;
  const currentModule = await readFile(moduleFile, 'utf8').catch(error => { if (error.code === 'ENOENT') return null; throw error; });
  if (currentModule !== expected) {
    if (check) throw new Error('Asset URLs are stale. Run: node scripts/doreumi/build-cache-assets.mjs');
    await mkdir(path.dirname(moduleFile), { recursive: true });
    await writeFile(moduleFile, expected);
  }
}

if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) {
  await buildCacheAssets(root, process.argv.includes('--check'));
}
